def plot_qft_scaling():
    print("2. QFT scaling")

    filename = "qft_scaling.csv"
    df = read_csv(filename)

    require_columns(
        df,
        filename,
        ["qubits"],
    )

    time_col = first_existing_column(
        df,
        [
            "qft_ms",
            "qft_us",
            "runtime_ms",
            "time_ms",
            "duration_ms",
            "qft_time_ms",
            "execution_ms",
            "execution_us",
        ],
    )

    if time_col is None:
        raise ValueError(
            f"\nCould not find a QFT timing column in {filename}.\n\n"
            f"Available columns:\n"
            f"  {list(df.columns)}\n\n"
            f"Expected one of:\n"
            f"  qft_ms\n"
            f"  qft_us\n"
            f"  runtime_ms\n"
            f"  time_ms\n"
            f"  duration_ms\n"
            f"  qft_time_ms\n"
            f"  execution_ms\n"
            f"  execution_us"
        )

    x, y = clean_xy(df, "qubits", time_col)

    if len(x) == 0:
        raise ValueError(
            f"No valid numeric QFT timing data found in {filename}."
        )

    fig, ax = plt.subplots(figsize=(8, 5))

    ax.semilogy(
        x,
        y,
        "o-",
        label="QFT",
    )

    if time_col.endswith("_us"):
        unit = "µs"
    else:
        unit = "ms"

    ax.set_xlabel("Number of Qubits")
    ax.set_ylabel(f"QFT Runtime ({unit})")
    ax.set_title(
        "Sirraya QuTub Quantum Fourier Transform Scaling"
    )

    ax.set_xticks(x)

    ax.legend()

    fig.tight_layout()
    save_figure(fig, "qft_scaling.png")



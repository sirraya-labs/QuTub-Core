def banner(title):
    print()
    print("=" * 72)
    print(title)
    print("=" * 72)


def require_file(filename):
    path = DATA_DIR / filename

    if not path.exists():
        raise FileNotFoundError(
            f"\nRequired dataset not found:\n"
            f"  {path}\n\n"
            f"Run the Rust generator first:\n"
            f"  cargo run --release --example visualization"
        )

    return path


def read_csv(filename):
    path = require_file(filename)
    df = pd.read_csv(path)

    if df.empty:
        raise ValueError(
            f"\nDataset is empty:\n"
            f"  {path}"
        )

    return df


def require_columns(df, filename, columns):
    missing = [c for c in columns if c not in df.columns]

    if missing:
        raise ValueError(
            f"\nDataset schema mismatch:\n"
            f"  {DATA_DIR / filename}\n\n"
            f"Missing columns:\n"
            f"  {missing}\n\n"
            f"Available columns:\n"
            f"  {list(df.columns)}"
        )


def save_figure(fig, filename):
    path = OUTPUT_DIR / filename
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    print(f"  -> {path}")


def first_existing_column(df, candidates):
    """
    Return the first candidate column that exists.
    """
    for name in candidates:
        if name in df.columns:
            return name

    return None


def numeric_series(df, column):
    """
    Convert a dataframe column to numeric values.

    Invalid values become NaN and are removed by the caller
    when appropriate.
    """
    return pd.to_numeric(df[column], errors="coerce")


def clean_xy(df, x_column, y_column):
    """
    Return finite numeric x/y arrays.
    """
    x = numeric_series(df, x_column)
    y = numeric_series(df, y_column)

    mask = np.isfinite(x) & np.isfinite(y)

    return x[mask].to_numpy(), y[mask].to_numpy()



def plot_noise_vs_purity():
    print("7. Noise vs purity")

    filename = "noise_vs_purity.csv"
    df = read_csv(filename)

    # Actual schema observed:
    #
    # noise_probability
    # purity
    # von_neumann_entropy
    #
    # Previous script incorrectly expected:
    #
    # probability
    #

    noise_col = first_existing_column(
        df,
        [
            "noise_probability",
            "probability",
            "noise_strength",
            "noise",
            "p",
            "gamma",
        ],
    )

    if noise_col is None:
        raise ValueError(
            f"\nCould not find noise-probability column "
            f"in {filename}.\n\n"
            f"Available columns:\n"
            f"  {list(df.columns)}\n\n"
            f"Expected one of:\n"
            f"  noise_probability\n"
            f"  probability\n"
            f"  noise_strength\n"
            f"  noise\n"
            f"  p\n"
            f"  gamma"
        )

    purity_col = first_existing_column(
        df,
        [
            "purity",
            "state_purity",
        ],
    )

    if purity_col is None:
        raise ValueError(
            f"\nCould not find purity column in {filename}.\n\n"
            f"Available columns:\n"
            f"  {list(df.columns)}"
        )

    x, purity = clean_xy(
        df,
        noise_col,
        purity_col,
    )

    if len(x) == 0:
        raise ValueError(
            f"No valid noise/purity data found "
            f"in {filename}."
        )

    fig, ax = plt.subplots(
        figsize=(8, 5)
    )

    # ------------------------------------------------------------------
    # If the Rust generator contains channel/model information,
    # plot separate curves.
    # ------------------------------------------------------------------

    grouping_column = None

    for candidate in [
        "channel",
        "noise_model",
        "model",
        "channel_type",
    ]:
        if candidate in df.columns:
            grouping_column = candidate
            break

    if grouping_column is not None:

        for group_name, subset in df.groupby(
            grouping_column
        ):
            sx, sy = clean_xy(
                subset,
                noise_col,
                purity_col,
            )

            if len(sx) == 0:
                continue

            ax.plot(
                sx,
                sy,
                "o-",
                label=str(group_name),
            )

    else:

        ax.plot(
            x,
            purity,
            "o-",
            label="Numerical",
        )

    ax.set_xlabel(
        "Noise Probability"
    )

    ax.set_ylabel(
        "Purity"
    )

    ax.set_title(
        "Sirraya QuTub Noise-Induced Purity"
    )

    ax.legend()

    fig.tight_layout()

    save_figure(
        fig,
        "noise_vs_purity.png",
    )



def plot_state_vector_scaling():
    print("1. State-vector scaling")

    filename = "state_vector_scaling.csv"
    df = read_csv(filename)

    require_columns(
        df,
        filename,
        [
            "qubits",
            "state_dimension",
        ],
    )

    qubits = numeric_series(df, "qubits")
    dimension = numeric_series(df, "state_dimension")

    mask = np.isfinite(qubits) & np.isfinite(dimension)

    qubits = qubits[mask].to_numpy()
    dimension = dimension[mask].to_numpy()

    if len(qubits) == 0:
        raise ValueError(
            f"No valid numeric data found in {filename}."
        )

    fig, ax = plt.subplots(figsize=(8, 5))

    ax.semilogy(
        qubits,
        dimension,
        "o-",
        label="State-vector dimension",
    )

    ax.set_xlabel("Number of Qubits")
    ax.set_ylabel("State-Vector Dimension")
    ax.set_title("Sirraya QuTub State-Vector Scaling")

    ax.set_xticks(qubits)

    ax.legend(loc="upper left")

    # ------------------------------------------------------------------
    # Optional timing data.
    #
    # Actual observed schema:
    #
    # qubits
    # state_dimension
    # construction_ms
    # hadamard_chain_ms
    # ------------------------------------------------------------------

    timing_columns = []

    if "construction_ms" in df.columns:
        timing_columns.append("construction_ms")

    if "hadamard_chain_ms" in df.columns:
        timing_columns.append("hadamard_chain_ms")

    if timing_columns:
        ax2 = ax.twinx()

        for column in timing_columns:
            y = numeric_series(df.loc[mask], column).to_numpy()

            if column == "construction_ms":
                ax2.plot(
                    qubits,
                    y,
                    "s--",
                    label="Construction time",
                )

            elif column == "hadamard_chain_ms":
                ax2.plot(
                    qubits,
                    y,
                    "^-.",
                    label="Hadamard-chain time",
                )

        ax2.set_ylabel("Runtime (ms)")

        lines1, labels1 = ax.get_legend_handles_labels()
        lines2, labels2 = ax2.get_legend_handles_labels()

        ax.legend(
            lines1 + lines2,
            labels1 + labels2,
            loc="upper left",
        )

    fig.tight_layout()
    save_figure(fig, "state_vector_scaling.png")



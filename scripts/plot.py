def main():

    print(
        "Generating plots from Sirraya QuTub experimental data...\n"
    )

    print("Script directory:")
    print(f"  {SCRIPT_DIR}")

    print("\nDataset directory:")
    print(f"  {DATA_DIR}")

    print("\nOutput directory:")
    print(f"  {OUTPUT_DIR}")

    if not DATA_DIR.exists():

        print(
            "\nERROR: Dataset directory does not exist:\n"
            f"  {DATA_DIR}\n"
        )

        sys.exit(1)

    csv_files = sorted(
        DATA_DIR.glob("*.csv")
    )

    print("\nCSV files detected:")

    if not csv_files:

        print("  (none)")

        sys.exit(1)

    for path in csv_files:
        print(
            f"  - {path.name}"
        )

    banner(
        "PLOT GENERATION"
    )

    # ------------------------------------------------------------------
    # Run every plot independently.
    #
    # This is deliberate: one malformed/optional dataset should not
    # prevent the other valid experimental figures from being produced.
    # ------------------------------------------------------------------

    jobs = [
        (
            "State-vector scaling",
            plot_state_vector_scaling,
        ),
        (
            "QFT scaling",
            plot_qft_scaling,
        ),
        (
            "Fidelity vs circuit depth",
            plot_fidelity_vs_depth,
        ),
        (
            "Bell-state measurement distribution",
            plot_bell_distribution,
        ),
        (
            "GHZ entanglement",
            plot_ghz_entanglement,
        ),
        (
            "W-state validation",
            plot_w_state,
        ),
        (
            "Noise vs purity",
            plot_noise_vs_purity,
        ),
        (
            "Noise vs entropy",
            plot_noise_entropy,
        ),
    ]

    successful = []
    failed = []

    for name, function in jobs:

        try:

            function()

            successful.append(name)

        except Exception as exc:

            failed.append(
                (
                    name,
                    str(exc),
                )
            )

            print()
            print(
                f"  WARNING: {name} failed."
            )

            print(
                f"  Reason: {exc}"
            )

            print(
                "  Continuing with remaining plots."
            )

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------

    banner(
        "PLOT GENERATION SUMMARY"
    )

    print(
        f"Successful plots: "
        f"{len(successful)}"
    )

    for name in successful:
        print(
            f"  [PASS] {name}"
        )

    if failed:

        print()
        print(
            f"Failed plots: "
            f"{len(failed)}"
        )

        for name, reason in failed:
            print(
                f"  [FAIL] {name}"
            )
            print(
                f"         {reason}"
            )

    print()
    print(
        "Generated files:"
    )

    generated = sorted(
        OUTPUT_DIR.glob("*.png")
    )

    if generated:

        for path in generated:
            print(
                f"  - {path.name}"
            )

    else:

        print(
            "  (none)"
        )

    print()
    print(
        f"Output directory:"
    )
    print(
        f"  {OUTPUT_DIR}"
    )

    # ------------------------------------------------------------------
    # Important:
    #
    # Optional/missing schema issues do not crash the whole script.
    # But if nothing could be generated, return an error code.
    # ------------------------------------------------------------------

    if not successful:

        print()
        print(
            "ERROR: No plots were generated."
        )

        sys.exit(1)

    print()
    print(
        "Done."
    )


if __name__ == "__main__":
    main()
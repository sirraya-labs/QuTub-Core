def plot_ghz_entanglement():
    print("5. GHZ entanglement")

    filename = "ghz_entanglement.csv"
    df = read_csv(filename)

    # Actual Rust-generated schema:
    #
    # qubits
    # p_all_zero
    # p_all_ones
    # forbidden_probability
    #
    require_columns(
        df,
        filename,
        [
            "qubits",
            "p_all_zero",
            "p_all_ones",
            "forbidden_probability",
        ],
    )

    # Convert everything explicitly to numeric.
    qubits = pd.to_numeric(
        df["qubits"],
        errors="coerce",
    )

    p_zero = pd.to_numeric(
        df["p_all_zero"],
        errors="coerce",
    )

    p_ones = pd.to_numeric(
        df["p_all_ones"],
        errors="coerce",
    )

    forbidden = pd.to_numeric(
        df["forbidden_probability"],
        errors="coerce",
    )

    mask = (
        np.isfinite(qubits)
        & np.isfinite(p_zero)
        & np.isfinite(p_ones)
        & np.isfinite(forbidden)
    )

    qubits = qubits[mask].to_numpy()
    p_zero = p_zero[mask].to_numpy()
    p_ones = p_ones[mask].to_numpy()
    forbidden = forbidden[mask].to_numpy()

    if len(qubits) == 0:
        raise ValueError(
            f"No valid numeric GHZ data found in {filename}."
        )

    print(
        f"  GHZ rows: {len(qubits)}"
    )

    # ------------------------------------------------------------------
    # GHZ validation:
    #
    # |GHZ_n> = (|00...0> + |11...1>) / sqrt(2)
    #
    # Therefore:
    #
    # P(00...0) = 0.5
    # P(11...1) = 0.5
    # P(forbidden states) = 0
    # ------------------------------------------------------------------

    fig, axes = plt.subplots(
        1,
        2,
        figsize=(12, 4.8),
    )

    # ==================================================================
    # Panel 1 — Allowed GHZ measurement probabilities
    # ==================================================================

    axes[0].plot(
        qubits,
        p_zero,
        "o-",
        label="P(|00...0⟩)",
    )

    axes[0].plot(
        qubits,
        p_ones,
        "s-",
        label="P(|11...1⟩)",
    )

    axes[0].axhline(
        0.5,
        linestyle="--",
        linewidth=1,
        label="Theory = 0.5",
    )

    axes[0].set_xlabel(
        "Number of Qubits"
    )

    axes[0].set_ylabel(
        "Measurement Probability"
    )

    axes[0].set_title(
        "GHZ Allowed-State Probabilities"
    )

    axes[0].set_ylim(
        0.0,
        1.0,
    )

    axes[0].set_xticks(
        qubits
    )

    axes[0].legend()

    # ==================================================================
    # Panel 2 — Forbidden probability
    # ==================================================================

    axes[1].plot(
        qubits,
        forbidden,
        "o-",
        label="Forbidden probability",
    )

    axes[1].axhline(
        0.0,
        linestyle="--",
        linewidth=1,
        label="Theory = 0",
    )

    axes[1].set_xlabel(
        "Number of Qubits"
    )

    axes[1].set_ylabel(
        "Probability"
    )

    axes[1].set_title(
        "GHZ Forbidden-State Probability"
    )

    axes[1].set_xticks(
        qubits
    )

    # If numerical error is tiny, don't let matplotlib make the graph
    # look completely flat without context.
    max_forbidden = float(
        np.max(np.abs(forbidden))
    )

    if max_forbidden == 0.0:
        axes[1].set_ylim(
            -1e-12,
            1e-12,
        )
    else:
        margin = max(
            max_forbidden * 0.25,
            1e-12,
        )

        axes[1].set_ylim(
            min(0.0, float(np.min(forbidden)) - margin),
            float(np.max(forbidden)) + margin,
        )

    axes[1].legend()

    fig.suptitle(
        "Sirraya QuTub GHZ State Validation",
        fontsize=14,
    )

    fig.tight_layout()

    save_figure(
        fig,
        "ghz_entanglement.png",
    )


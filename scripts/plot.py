def plot_bell_distribution():
    print("4. Bell-state measurement distribution")

    filename = "bell_distribution.csv"
    df = read_csv(filename)

    # Actual schema:
    #
    # basis_state, probability
    #

    require_columns(
        df,
        filename,
        [
            "basis_state",
            "probability",
        ],
    )

    print(f"  Columns: {list(df.columns)}")

    labels = df["basis_state"].astype(str)

    probability = numeric_series(
        df,
        "probability",
    )

    mask = np.isfinite(probability)

    labels = labels[mask].to_numpy()
    probability = probability[mask].to_numpy()

    if len(probability) == 0:
        raise ValueError(
            f"No valid probability data found in {filename}."
        )

    fig, ax = plt.subplots(figsize=(7, 5))

    positions = np.arange(len(labels))

    ax.bar(
        positions,
        probability,
    )

    ax.set_xticks(positions)
    ax.set_xticklabels(labels)

    ax.set_xlabel("Computational Basis State")
    ax.set_ylabel("Probability")
    ax.set_title(
        "Bell-State Measurement Distribution"
    )

    upper = max(
        0.6,
        float(np.max(probability)) * 1.15,
    )

    ax.set_ylim(
        0,
        upper,
    )

    for i, value in enumerate(probability):
        ax.text(
            i,
            value + 0.015,
            f"{value:.3f}",
            ha="center",
            fontsize=10,
        )

    fig.tight_layout()
    save_figure(
        fig,
        "bell_distribution.png",
    )



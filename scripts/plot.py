def plot_fidelity_vs_depth():
    print("3. Fidelity vs circuit depth")

    filename = "fidelity_vs_depth.csv"
    df = read_csv(filename)

    require_columns(
        df,
        filename,
        ["depth"],
    )

    # Actual observed schema:
    #
    # depth
    # ideal_vs_perturbed_fidelity
    # trace_distance
    #
    fidelity_col = first_existing_column(
        df,
        [
            "fidelity",
            "ideal_vs_perturbed_fidelity",
            "self_fidelity",
        ],
    )

    if fidelity_col is None:
        raise ValueError(
            f"\nCould not find fidelity column in {filename}.\n\n"
            f"Available columns:\n"
            f"  {list(df.columns)}"
        )

    x, fidelity = clean_xy(
        df,
        "depth",
        fidelity_col,
    )

    if len(x) == 0:
        raise ValueError(
            f"No valid fidelity data found in {filename}."
        )

    fig, ax = plt.subplots(figsize=(8, 5))

    ax.plot(
        x,
        fidelity,
        "o-",
        label=fidelity_col.replace("_", " "),
    )

    ax.axhline(
        1.0,
        linestyle="--",
        linewidth=1,
        label="Ideal fidelity = 1",
    )

    ax.set_xlabel("Circuit Depth")
    ax.set_ylabel("Fidelity")
    ax.set_title(
        "Sirraya QuTub Fidelity vs Circuit Depth"
    )

    minimum = float(np.min(fidelity))
    maximum = float(np.max(fidelity))

    # If fidelity is extremely close to one, zoom in.
    if (
        maximum <= 1.000001
        and minimum >= 0.999
    ):
        span = maximum - minimum

        margin = max(
            span * 5.0,
            1e-6,
        )

        lower = max(
            0.0,
            minimum - margin,
        )

        upper = min(
            1.000001,
            maximum + margin,
        )

        ax.set_ylim(lower, upper)

    ax.legend()

    fig.tight_layout()
    save_figure(
        fig,
        "fidelity_vs_depth.png",
    )


